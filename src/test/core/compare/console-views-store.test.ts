/**
 * Issue #298: the Console's saved Views live in one store, shared by the Console and Compare,
 * so a View changed in either screen is the endpoint's View.
 */
import { expect } from 'chai';
import { ConsoleViewsStore, VIEWS_REGISTRY_KEY } from '../../../services/console/console-views-store';
import { MemoryKeyValueStore } from '../../../platform/memory/memory-key-value-store';
import type { APIEndpointConfig } from '../../../apiConfigManager';

const views = (name: string, extra: Record<string, unknown> = {}) => ({
    success: { activeView: name, views: [{ name, rowBasis: 'data.items', columns: [{ id: 'data.items.itemCode', source: 'current' }], ...extra }] },
    errors: { activeView: 'Root', views: [] },
});

function endpoints(initial: Partial<APIEndpointConfig> = {}) {
    let endpoint = { id: 'ep1', method: 'GET', path: '/api/items', ...initial } as APIEndpointConfig;
    const updates: Array<Partial<APIEndpointConfig>> = [];
    return {
        updates,
        getEndpoint: async (id: string) => (id === 'ep1' ? endpoint : undefined),
        updateEndpoint: async (_id: string, u: Partial<APIEndpointConfig>) => { updates.push(u); endpoint = { ...endpoint, ...u }; },
    };
}

describe('Console Views store (shared by Console and Compare)', () => {
    it('saves under the endpoint\'s method and path, and reads it back', async () => {
        const state = new MemoryKeyValueStore();
        const eps = endpoints();
        const store = new ConsoleViewsStore({ state, endpoints: eps });
        await store.save('ep1', views('Dimensions'));
        expect(await store.load('ep1')).to.deep.equal(views('Dimensions'));
        const registry = state.get<{ scopes: Record<string, unknown> }>(VIEWS_REGISTRY_KEY)!;
        expect(Object.keys(registry.scopes)).to.deep.equal(['GET /api/items']);
    });

    it('mirrors the Views onto the endpoint, without the auto-made DEFAULT', async () => {
        const eps = endpoints();
        const store = new ConsoleViewsStore({ state: new MemoryKeyValueStore(), endpoints: eps });
        await store.save('ep1', views('DEFAULT', { isAutoGenerated: true }));
        const mirrored = eps.updates[0].consoleViews as unknown as { success: { views: unknown[] } };
        expect(mirrored.success.views).to.deep.equal([]);
    });

    it('falls back to Views embedded on the endpoint, and keeps them in the registry from then on', async () => {
        const state = new MemoryKeyValueStore();
        const eps = endpoints({ consoleViews: views('Imported') as unknown as APIEndpointConfig['consoleViews'] });
        const store = new ConsoleViewsStore({ state, endpoints: eps });
        expect(await store.load('ep1')).to.deep.equal(views('Imported'));
        expect(state.get<{ scopes: Record<string, unknown> }>(VIEWS_REGISTRY_KEY)!.scopes['GET /api/items']).to.deep.equal(views('Imported'));
    });

    it('keeps a deleted endpoint\'s Views under its own orphan scope', async () => {
        const store = new ConsoleViewsStore({ state: new MemoryKeyValueStore(), endpoints: endpoints() });
        await store.save('gone', views('Old'));
        expect(await store.load('gone')).to.deep.equal(views('Old'));
        expect(await store.resolveScopeKey('gone')).to.equal('orphan:gone');
    });
});
