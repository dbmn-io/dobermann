import { expect } from 'chai';
import { getEndpointViewScopeKey, stripAutoDefaultForMirror } from '../../../../services/console/view-scope-key';

describe('getEndpointViewScopeKey - Issue #237', () => {
    it('uppercases the method', () => {
        expect(getEndpointViewScopeKey('get', '/lpn/search')).to.equal('GET /lpn/search');
        expect(getEndpointViewScopeKey('Post', '/lpn/search')).to.equal('POST /lpn/search');
    });

    it('trims whitespace on method and path', () => {
        expect(getEndpointViewScopeKey(' POST ', '  /lpn/search  ')).to.equal('POST /lpn/search');
    });

    it('preserves the leading slash on path', () => {
        expect(getEndpointViewScopeKey('GET', '/items/{itemId}')).to.equal('GET /items/{itemId}');
    });

    it('does not normalize path-template placeholders', () => {
        // Issue #237: paths are matched exactly. {id} and {itemId} are different scopes.
        expect(getEndpointViewScopeKey('GET', '/items/{id}'))
            .to.not.equal(getEndpointViewScopeKey('GET', '/items/{itemId}'));
    });

    it('treats the same method+path as the same scope regardless of case', () => {
        expect(getEndpointViewScopeKey('post', '/x'))
            .to.equal(getEndpointViewScopeKey('POST', '/x'));
    });

    it('treats different methods on the same path as different scopes', () => {
        expect(getEndpointViewScopeKey('GET', '/x'))
            .to.not.equal(getEndpointViewScopeKey('POST', '/x'));
    });
});

describe('stripAutoDefaultForMirror - Issue #242', () => {
    it('removes auto-generated DEFAULT views from each tab', () => {
        const views = {
            success: {
                activeView: 'DEFAULT',
                views: [
                    { name: 'DEFAULT', rowBasis: 'data.items', columns: [], isAutoGenerated: true },
                    { name: 'PO Lines', rowBasis: 'data.lines', columns: [], isAutoGenerated: false }
                ]
            },
            errors: {
                activeView: 'DEFAULT',
                views: [
                    { name: 'DEFAULT', rowBasis: 'root', columns: [], isAutoGenerated: true }
                ]
            }
        };
        const out = stripAutoDefaultForMirror(views) as any;
        expect(out.success.views).to.have.length(1);
        expect(out.success.views[0].name).to.equal('PO Lines');
        expect(out.errors.views).to.have.length(0);
    });

    it('preserves a user-edited DEFAULT (isAutoGenerated false)', () => {
        const views = {
            success: {
                activeView: 'DEFAULT',
                views: [
                    { name: 'DEFAULT', rowBasis: 'data.items', columns: [{ id: 'a' }], isAutoGenerated: false }
                ]
            },
            errors: { activeView: '', views: [] }
        };
        const out = stripAutoDefaultForMirror(views) as any;
        expect(out.success.views).to.have.length(1);
        expect(out.success.views[0].isAutoGenerated).to.equal(false);
    });

    it('preserves auto-gen views that are not named DEFAULT', () => {
        const views = {
            success: {
                activeView: 'data.items',
                views: [
                    { name: 'data.items', rowBasis: 'data.items', columns: [], isAutoGenerated: true }
                ]
            },
            errors: { activeView: '', views: [] }
        };
        const out = stripAutoDefaultForMirror(views) as any;
        expect(out.success.views).to.have.length(1);
        expect(out.success.views[0].name).to.equal('data.items');
    });

    it('clears activeView when stripped DEFAULT was active', () => {
        const views = {
            success: {
                activeView: 'DEFAULT',
                views: [
                    { name: 'DEFAULT', rowBasis: 'data.items', columns: [], isAutoGenerated: true },
                    { name: 'PO Lines', rowBasis: 'data.lines', columns: [], isAutoGenerated: false }
                ]
            },
            errors: { activeView: '', views: [] }
        };
        const out = stripAutoDefaultForMirror(views) as any;
        expect(out.success.activeView).to.equal('PO Lines');
    });

    it('does not mutate the input', () => {
        const views = {
            success: {
                activeView: 'DEFAULT',
                views: [
                    { name: 'DEFAULT', rowBasis: 'data.items', columns: [], isAutoGenerated: true }
                ]
            },
            errors: { activeView: '', views: [] }
        };
        stripAutoDefaultForMirror(views);
        expect(views.success.views).to.have.length(1);
        expect(views.success.activeView).to.equal('DEFAULT');
    });

    it('handles non-object input safely', () => {
        expect(stripAutoDefaultForMirror(null)).to.equal(null);
        expect(stripAutoDefaultForMirror(undefined)).to.equal(undefined);
        expect(stripAutoDefaultForMirror('not-an-object')).to.equal('not-an-object');
    });
});
