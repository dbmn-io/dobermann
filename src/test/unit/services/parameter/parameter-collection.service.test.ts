/**
 * Unit tests for ParameterCollectionService
 * Tests extraction of user variables and parameter collection logic
 */

import { assert } from 'chai';
import { ParameterCollectionService } from '../../../../services/parameter/parameter-collection.service';
import { IExtensionDiagnosticLogger } from '../../../../services/logging/extension-diagnostic-logger.interface';

describe('ParameterCollectionService', () => {
    let service: ParameterCollectionService;
    let mockLogger: IExtensionDiagnosticLogger;

    beforeEach(() => {
        mockLogger = {
            debug: () => {},
            info: () => {},
            warn: () => {},
            error: () => {},
            trace: () => {},
            show: () => {},
            clear: () => {},
            dispose: () => {}
        } as IExtensionDiagnosticLogger;

        service = new ParameterCollectionService(mockLogger);
    });

    describe('extractUserVariablesWithTypes', () => {
        it('should extract variables with type information', () => {
            const template = '{"name": "{{userName:string}}", "age": "{{userAge:number}}", "active": "{{isActive:boolean}}"}';
            const variables = service.extractUserVariablesWithTypes(template);
            
            assert.lengthOf(variables, 3);
            assert.deepEqual(variables[0], { name: 'userName', isAutoGenerated: false, typeHint: 'string' });
            assert.deepEqual(variables[1], { name: 'userAge', isAutoGenerated: false, typeHint: 'number' });
            assert.deepEqual(variables[2], { name: 'isActive', isAutoGenerated: false, typeHint: 'boolean' });
        });

        it('should handle variables without type hints', () => {
            const template = '{"name": "{{userName}}", "age": "{{userAge:number}}"}';
            const variables = service.extractUserVariablesWithTypes(template);
            
            assert.lengthOf(variables, 2);
            assert.deepEqual(variables[0], { name: 'userName', isAutoGenerated: false, typeHint: undefined });
            assert.deepEqual(variables[1], { name: 'userAge', isAutoGenerated: false, typeHint: 'number' });
        });

        it('should exclude A8 auto-generated variables with types', () => {
            const template = '{"id": "{{A8:sequence}}", "name": "{{userName:string}}", "created": "{{A8:datetime}}"}';
            const variables = service.extractUserVariablesWithTypes(template);
            
            assert.lengthOf(variables, 1);
            assert.deepEqual(variables[0], { name: 'userName', isAutoGenerated: false, typeHint: 'string' });
        });

        it('should handle date type variables', () => {
            const template = '{"created": "{{createdDate:date}}", "name": "{{userName}}"}';
            const variables = service.extractUserVariablesWithTypes(template);
            
            assert.lengthOf(variables, 2);
            assert.deepEqual(variables[0], { name: 'createdDate', isAutoGenerated: false, typeHint: 'date' });
            assert.deepEqual(variables[1], { name: 'userName', isAutoGenerated: false, typeHint: undefined });
        });
    });

    describe('extractUserVariables', () => {
        it('should extract simple variables', () => {
            const template = '{"name": "{{userName}}", "age": "{{userAge}}"}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, ['userName', 'userAge']);
        });

        it('should extract variables with type hints', () => {
            const template = '{"name": "{{userName:string}}", "age": "{{userAge:number}}"}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, ['userName', 'userAge']);
        });

        it('should exclude A8 auto-generated variables', () => {
            const template = '{"id": "{{A8:sequence}}", "name": "{{userName}}", "created": "{{A8:datetime}}"}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, ['userName']);
        });

        it('should exclude V8 auto-generated variables (if they exist)', () => {
            const template = '{"id": "{{V8:sequence}}", "name": "{{userName}}", "other": "{{V8:other}}"}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, ['userName']);
        });

        it('should handle duplicate variables', () => {
            const template = '{"name": "{{userName}}", "displayName": "{{userName}}", "age": "{{userAge}}"}';
            const variables = service.extractUserVariables(template);
            
            // Should only include each unique variable once
            assert.deepEqual(variables, ['userName', 'userAge']);
        });

        it('should ignore conditional and loop syntax', () => {
            const template = '{"items": [{{#each items}}"{{name}}"{{/each}}], "name": "{{userName}}"}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, ['name', 'userName']);
        });

        it('should return empty array for template without variables', () => {
            const template = '{"static": "value", "number": 123}';
            const variables = service.extractUserVariables(template);
            
            assert.deepEqual(variables, []);
        });

        it('should return empty array for empty template', () => {
            const variables = service.extractUserVariables('');
            assert.deepEqual(variables, []);
        });
    });

    describe('replaceVariables', () => {
        it('should replace simple variables', () => {
            const template = '{"name": "{{userName}}", "age": "{{userAge}}"}';
            const parameters = { userName: 'John', userAge: '25' };
            
            const result = service.replaceVariables(template, parameters);
            
            assert.equal(result, '{"name": "John", "age": "25"}');
        });

        it('should replace variables with type hints', () => {
            const template = '{"name": "{{userName:string}}", "age": {{userAge:number}}}';
            const parameters = { userName: 'John', userAge: 25 };
            
            const result = service.replaceVariables(template, parameters);
            
            assert.equal(result, '{"name": "John", "age": 25}');
        });

        it('should handle multiple occurrences of same variable', () => {
            const template = '{"name": "{{userName}}", "displayName": "{{userName}}", "greeting": "Hello {{userName}}"}';
            const parameters = { userName: 'John' };
            
            const result = service.replaceVariables(template, parameters);
            
            assert.equal(result, '{"name": "John", "displayName": "John", "greeting": "Hello John"}');
        });

        it('should not affect auto-generated variables', () => {
            const template = '{"id": "{{A8:sequence}}", "name": "{{userName}}", "created": "{{A8:datetime}}"}';
            const parameters = { userName: 'John' };
            
            const result = service.replaceVariables(template, parameters);
            
            assert.equal(result, '{"id": "{{A8:sequence}}", "name": "John", "created": "{{A8:datetime}}"}');
        });

        it('should handle special regex characters in variable names', () => {
            const template = '{"value": "{{user.name}}", "other": "{{user_name}}"}';
            const parameters = { 'user.name': 'John', 'user_name': 'Jane' };
            
            const result = service.replaceVariables(template, parameters);
            
            assert.equal(result, '{"value": "John", "other": "Jane"}');
        });

        it('should return original template if no parameters provided', () => {
            const template = '{"name": "{{userName}}"}';
            
            const result = service.replaceVariables(template, {});
            
            assert.equal(result, template);
        });

        it('should return original template if template is empty', () => {
            const result = service.replaceVariables('', { userName: 'John' });
            
            assert.equal(result, '');
        });
    });

    describe('integration scenarios', () => {
        it('should handle complex template with mixed variables', () => {
            const template = JSON.stringify({
                id: '{{A8:sequence}}',
                user: {
                    name: '{{userName:string}}',
                    age: '{{userAge:number}}',
                    active: '{{isActive:boolean}}'
                },
                items: [
                    {
                        name: '{{itemName}}',
                        quantity: '{{quantity:number}}'
                    }
                ],
                createdAt: '{{A8:datetime}}'
            }, null, 2);

            const userVariables = service.extractUserVariables(template);
            assert.deepEqual(userVariables, ['userName', 'userAge', 'isActive', 'itemName', 'quantity']);

            const parameters = {
                userName: 'John Doe',
                userAge: 30,
                isActive: true,
                itemName: 'Widget',
                quantity: 5
            };

            const result = service.replaceVariables(template, parameters);
            
            // Verify that user variables are replaced but A8 variables remain
            assert.include(result, 'John Doe');
            assert.include(result, '30');
            assert.include(result, 'true');
            assert.include(result, 'Widget');
            assert.include(result, '5');
            assert.include(result, '{{A8:sequence}}');
            assert.include(result, '{{A8:datetime}}');
        });
    });

    describe('type validation and conversion', () => {
        it('should validate number types correctly', () => {
            const service = new ParameterCollectionService(mockLogger);
            
            // Access private method for testing
            const validateMethod = (service as any).validateValueForType;
            
            assert.isTrue(validateMethod('123', 'number').valid);
            assert.isTrue(validateMethod('-45', 'number').valid);
            assert.isTrue(validateMethod('3.14', 'number').valid);
            assert.isTrue(validateMethod('0', 'number').valid);
            
            assert.isFalse(validateMethod('abc', 'number').valid);
            assert.isFalse(validateMethod('12.34.56', 'number').valid);
            assert.include(validateMethod('abc', 'number').error, 'valid number');
        });

        it('should validate boolean types correctly', () => {
            const service = new ParameterCollectionService(mockLogger);
            const validateMethod = (service as any).validateValueForType;
            
            // Valid boolean values
            assert.isTrue(validateMethod('true', 'boolean').valid);
            assert.isTrue(validateMethod('false', 'boolean').valid);
            assert.isTrue(validateMethod('1', 'boolean').valid);
            assert.isTrue(validateMethod('0', 'boolean').valid);
            assert.isTrue(validateMethod('yes', 'boolean').valid);
            assert.isTrue(validateMethod('no', 'boolean').valid);
            assert.isTrue(validateMethod('TRUE', 'boolean').valid); // case insensitive
            
            // Invalid boolean values
            assert.isFalse(validateMethod('maybe', 'boolean').valid);
            assert.isFalse(validateMethod('2', 'boolean').valid);
            assert.include(validateMethod('maybe', 'boolean').error, 'true/false');
        });

        it('should validate date types correctly', () => {
            const service = new ParameterCollectionService(mockLogger);
            const validateMethod = (service as any).validateValueForType;
            
            // Valid date formats
            assert.isTrue(validateMethod('2024-01-15', 'date').valid);
            assert.isTrue(validateMethod('Jan 15, 2024', 'date').valid);
            assert.isTrue(validateMethod('2024/01/15', 'date').valid);
            
            // Invalid date values
            assert.isFalse(validateMethod('not-a-date', 'date').valid);
            assert.isFalse(validateMethod('2024-13-40', 'date').valid);
            assert.include(validateMethod('not-a-date', 'date').error, 'valid date');
        });

        it('should convert values to correct types', () => {
            const service = new ParameterCollectionService(mockLogger);
            const convertMethod = (service as any).convertValueToType;
            
            // Number conversion
            assert.strictEqual(convertMethod('123', 'number'), 123);
            assert.strictEqual(convertMethod('3.14', 'number'), 3.14);
            assert.strictEqual(convertMethod('-45', 'number'), -45);
            
            // Boolean conversion
            assert.strictEqual(convertMethod('true', 'boolean'), true);
            assert.strictEqual(convertMethod('false', 'boolean'), false);
            assert.strictEqual(convertMethod('1', 'boolean'), true);
            assert.strictEqual(convertMethod('0', 'boolean'), false);
            assert.strictEqual(convertMethod('yes', 'boolean'), true);
            assert.strictEqual(convertMethod('no', 'boolean'), false);
            
            // Date conversion (should return ISO string)
            const dateResult = convertMethod('2024-01-15', 'date');
            assert.isString(dateResult);
            assert.include(dateResult, '2024-01-15');
            
            // String conversion (unchanged)
            assert.strictEqual(convertMethod('hello', 'string'), 'hello');
            assert.strictEqual(convertMethod('hello', undefined), 'hello');
        });

        it('should provide appropriate example values', () => {
            const service = new ParameterCollectionService(mockLogger);
            const getExampleMethod = (service as any).getExampleValue;
            
            assert.equal(getExampleMethod('string'), 'Hello World');
            assert.equal(getExampleMethod('number'), '123');
            assert.equal(getExampleMethod('boolean'), 'true (or false, 1, 0, yes, no)');
            assert.equal(getExampleMethod('date'), '2024-01-15 (or Jan 15 2024, 01/15/2024)');
            assert.isUndefined(getExampleMethod('unknown'));
            assert.isUndefined(getExampleMethod());
        });

        it('should provide context-aware example values', () => {
            const service = new ParameterCollectionService(mockLogger);
            const getExampleMethod = (service as any).getExampleValue;
            
            // Context-aware string examples
            assert.equal(getExampleMethod('string', 'userName'), 'John Doe');
            assert.equal(getExampleMethod('string', 'userEmail'), 'john@example.com');
            assert.equal(getExampleMethod('string', 'phoneNumber'), '+1-555-123-4567');
            assert.equal(getExampleMethod('string', 'city'), 'New York');
            
            // Context-aware number examples
            assert.equal(getExampleMethod('number', 'userAge'), '25');
            assert.equal(getExampleMethod('number', 'productPrice'), '99.99');
            assert.equal(getExampleMethod('number', 'quantity'), '10');
            assert.equal(getExampleMethod('number', 'percentageValue'), '85');
            
            // Context-aware boolean examples
            assert.equal(getExampleMethod('boolean', 'isActive'), 'true');
            assert.equal(getExampleMethod('boolean', 'isDeleted'), 'false');
        });
    });

    describe('URL template variable extraction', () => {
        it('should extract variables from URL paths', () => {
            const url = '/api/v1/orders/{{orderId}}/items/{{itemId:number}}';
            const variables = service.extractVariablesFromUrl(url);

            assert.lengthOf(variables, 2);
            assert.deepEqual(variables[0], { name: 'orderId', isAutoGenerated: false, typeHint: undefined, sources: ['url'] });
            assert.deepEqual(variables[1], { name: 'itemId', isAutoGenerated: false, typeHint: 'number', sources: ['url'] });
        });

        it('should handle URLs without variables', () => {
            const url = '/api/v1/orders/fixed/path';
            const variables = service.extractVariablesFromUrl(url);

            assert.lengthOf(variables, 0);
        });

        it('should handle empty or invalid URLs', () => {
            assert.lengthOf(service.extractVariablesFromUrl(''), 0);
            assert.lengthOf(service.extractVariablesFromUrl(null as any), 0);
            assert.lengthOf(service.extractVariablesFromUrl(undefined as any), 0);
        });
    });

    describe('Query parameter template variable extraction', () => {
        it('should extract variables from query parameter values', () => {
            const queryParams = {
                page: '{{pageNumber:number}}',
                filter: '{{searchTerm:string}}',
                limit: '10' // no variables
            };
            const variables = service.extractVariablesFromQueryParams(queryParams);

            assert.lengthOf(variables, 2);
            assert.deepEqual(variables[0], { name: 'pageNumber', isAutoGenerated: false, typeHint: 'number', sources: ['query_param:page'] });
            assert.deepEqual(variables[1], { name: 'searchTerm', isAutoGenerated: false, typeHint: 'string', sources: ['query_param:filter'] });
        });

        it('should handle query params without variables', () => {
            const queryParams = {
                page: '1',
                limit: '10'
            };
            const variables = service.extractVariablesFromQueryParams(queryParams);

            assert.lengthOf(variables, 0);
        });

        it('should handle empty query params', () => {
            assert.lengthOf(service.extractVariablesFromQueryParams({}), 0);
            assert.lengthOf(service.extractVariablesFromQueryParams(null as any), 0);
            assert.lengthOf(service.extractVariablesFromQueryParams(undefined as any), 0);
        });
    });

    describe('Header template variable extraction', () => {
        it('should extract variables from header values', () => {
            const headers = {
                'Authorization': 'Bearer {{authToken:string}}',
                'X-User-ID': '{{userId:number}}',
                'Content-Type': 'application/json' // no variables
            };
            const variables = service.extractVariablesFromHeaders(headers);

            assert.lengthOf(variables, 2);
            assert.deepEqual(variables[0], { name: 'authToken', isAutoGenerated: false, typeHint: 'string', sources: ['header:Authorization'] });
            assert.deepEqual(variables[1], { name: 'userId', isAutoGenerated: false, typeHint: 'number', sources: ['header:X-User-ID'] });
        });

        it('should handle headers without variables', () => {
            const headers = {
                'Content-Type': 'application/json',
                'Accept': 'application/json'
            };
            const variables = service.extractVariablesFromHeaders(headers);

            assert.lengthOf(variables, 0);
        });

        it('should handle empty headers', () => {
            assert.lengthOf(service.extractVariablesFromHeaders({}), 0);
            assert.lengthOf(service.extractVariablesFromHeaders(null as any), 0);
            assert.lengthOf(service.extractVariablesFromHeaders(undefined as any), 0);
        });
    });

    describe('URL variable replacement with encoding', () => {
        it('should replace variables in URLs with proper encoding', () => {
            const url = '/api/v1/orders/{{orderId}}/items/{{itemName}}';
            const parameters = { orderId: '123', itemName: 'Widget & Co.' };

            const result = service.replaceVariablesInUrl(url, parameters);

            assert.equal(result, '/api/v1/orders/123/items/Widget%20%26%20Co.');
        });

        it('should handle special characters in URL variables', () => {
            const url = '/api/search/{{query}}';
            const parameters = { query: 'hello world!@#$%^&*()' };

            const result = service.replaceVariablesInUrl(url, parameters);

            assert.equal(result, '/api/search/hello%20world!%40%23%24%25%5E%26*()');
        });

        it('should return original URL if no parameters', () => {
            const url = '/api/v1/orders/{{orderId}}';

            const result = service.replaceVariablesInUrl(url, {});

            assert.equal(result, url);
        });
    });

    describe('Query parameter variable replacement with encoding', () => {
        it('should replace variables in query parameters with proper encoding', () => {
            const queryParams = {
                search: '{{searchTerm}}',
                category: '{{categoryName}}'
            };
            const parameters = { searchTerm: 'hello world', categoryName: 'Books & Media' };

            const result = service.replaceVariablesInQueryParams(queryParams, parameters);

            assert.deepEqual(result, {
                search: 'hello%20world',
                category: 'Books%20%26%20Media'
            });
        });

        it('should handle mixed query params with and without variables', () => {
            const queryParams = {
                search: '{{searchTerm}}',
                limit: '10',
                sort: 'created_{{sortOrder}}'
            };
            const parameters = { searchTerm: 'test query', sortOrder: 'desc' };

            const result = service.replaceVariablesInQueryParams(queryParams, parameters);

            assert.deepEqual(result, {
                search: 'test%20query',
                limit: '10',
                sort: 'created_desc'
            });
        });
    });

    describe('Header variable replacement without encoding', () => {
        it('should replace variables in headers without encoding', () => {
            const headers = {
                'Authorization': 'Bearer {{authToken}}',
                'X-User-ID': '{{userId}}'
            };
            const parameters = { authToken: 'abc123!@#', userId: '456' };

            const result = service.replaceVariablesInHeaders(headers, parameters);

            assert.deepEqual(result, {
                'Authorization': 'Bearer abc123!@#',
                'X-User-ID': '456'
            });
        });

        it('should handle mixed headers with and without variables', () => {
            const headers = {
                'Authorization': 'Bearer {{authToken}}',
                'Content-Type': 'application/json',
                'X-Custom': 'prefix-{{customValue}}-suffix'
            };
            const parameters = { authToken: 'token123', customValue: 'test' };

            const result = service.replaceVariablesInHeaders(headers, parameters);

            assert.deepEqual(result, {
                'Authorization': 'Bearer token123',
                'Content-Type': 'application/json',
                'X-Custom': 'prefix-test-suffix'
            });
        });
    });

    describe('Multi-source parameter collection', () => {
        it('should collect parameters from all sources and deduplicate', async () => {
            // The values form answers every field
            const service = new ParameterCollectionService(mockLogger, () => ({
                showModal: async spec => ({ actionId: 'run', fields: Object.fromEntries((spec.fields || []).map(f => [f.id, 'test-value'])) })
            }));

            const bodyTemplate = '{"name": "{{userName:string}}"}';
            const url = '/api/users/{{userName}}';
            const queryParams = { search: '{{searchTerm:string}}' };
            const headers = { 'X-User': '{{userName}}' };

            try {
                const result = await service.collectParameters(
                    bodyTemplate,
                    'Test Endpoint',
                    url,
                    queryParams,
                    headers
                );

                // Should deduplicate userName variable across sources
                assert.isFalse(result.cancelled);
                assert.isObject(result.parameters);
                assert.property(result.parameters, 'userName');
                assert.property(result.parameters, 'searchTerm');
                assert.lengthOf(Object.keys(result.parameters!), 2);
            } finally {
                // nothing to restore
            }
        });

        it('should handle sources with no variables', async () => {
            const bodyTemplate = '';
            const url = '/api/fixed/path';
            const queryParams = { limit: '10' };
            const headers = { 'Content-Type': 'application/json' };

            const result = await service.collectParameters(
                bodyTemplate,
                'Test Endpoint',
                url,
                queryParams,
                headers
            );

            assert.isFalse(result.cancelled);
            assert.deepEqual(result.parameters, {});
        });
    });

    describe('formatModifier extraction (Run API modal reuse of batch-prep rules)', () => {
        it('propagates number modifier chain (|int|>0) to formatModifier', () => {
            const template = '{"qty": "{{qty:number|int|>0}}"}';
            const variables = service.extractUserVariablesWithTypes(template);

            assert.lengthOf(variables, 1);
            assert.equal(variables[0].name, 'qty');
            assert.equal(variables[0].typeHint, 'number');
            assert.equal(variables[0].formatModifier, 'int|>0');
        });

        it('propagates string length modifier (|3-50) to formatModifier', () => {
            const template = '{"name": "{{userName:string|3-50}}"}';
            const variables = service.extractUserVariablesWithTypes(template);

            assert.lengthOf(variables, 1);
            assert.equal(variables[0].formatModifier, '3-50');
        });

        it('propagates opt / null empty-behaviour markers', () => {
            const template = '{"nickname": "{{nickname:string|opt}}", "note": "{{note:string|null}}"}';
            const variables = service.extractUserVariablesWithTypes(template);

            assert.lengthOf(variables, 2);
            assert.equal(variables[0].formatModifier, 'opt');
            assert.equal(variables[1].formatModifier, 'null');
        });

        it('omits formatModifier entirely when the template declares none', () => {
            const template = '{"name": "{{userName:string}}"}';
            const variables = service.extractUserVariablesWithTypes(template);

            assert.lengthOf(variables, 1);
            assert.notProperty(variables[0], 'formatModifier');
        });
    });

    describe('validateFieldsWithBatchPrep (Run API modal validation gate)', () => {
        // Access the private method directly — it's a thin adapter over
        // batch prep's parseModifiers + applyModifiers, and behaviour matters
        // enough to lock in with tests.
        // eslint-disable-next-line @typescript-eslint/no-explicit-any
        const validate = (variables: unknown[], fields: Record<string, string>) =>
            (service as unknown as { validateFieldsWithBatchPrep: (v: unknown[], f: Record<string, string>) => Record<string, string> })
                .validateFieldsWithBatchPrep(variables, fields);

        it('flags empty non-opt/null fields as Required', () => {
            const variables = [
                { name: 'sku', isAutoGenerated: false, typeHint: 'string' }
            ];
            const errors = validate(variables, { sku: '' });

            assert.equal(errors.sku, 'Required');
        });

        it('allows empty values on |opt fields', () => {
            const variables = [
                { name: 'nickname', isAutoGenerated: false, typeHint: 'string', formatModifier: 'opt' }
            ];
            const errors = validate(variables, { nickname: '' });

            assert.notProperty(errors, 'nickname');
        });

        it('allows empty values on |null fields', () => {
            const variables = [
                { name: 'note', isAutoGenerated: false, typeHint: 'string', formatModifier: 'null' }
            ];
            const errors = validate(variables, { note: '' });

            assert.notProperty(errors, 'note');
        });

        it('runs the value through applyModifiers when non-empty (rejects -1 on |>0)', () => {
            const variables = [
                { name: 'qty', isAutoGenerated: false, typeHint: 'number', formatModifier: '>0' }
            ];
            const errors = validate(variables, { qty: '-1' });

            assert.property(errors, 'qty');
            // Batch prep's own applyModifiers wording — mentions "greater than 0".
            // Locking in that we're passing through its message rather than our own.
            assert.match(errors.qty, /greater than/i);
        });

        it('passes valid values (positive number with |>0)', () => {
            const variables = [
                { name: 'qty', isAutoGenerated: false, typeHint: 'number', formatModifier: '>0' }
            ];
            const errors = validate(variables, { qty: '42' });

            assert.deepEqual(errors, {});
        });
    });
});