/**
 * Postman Collection Parser
 *
 * Converts a Postman v2.1 collection JSON into a synthetic ImportPackage
 * that can flow through the existing import-export pipeline.
 *
 * GitHub Issue: #189
 */

import { APIEndpointConfig } from '../../apiConfigManager';
import { generateEndpointId } from '../../apiConfigManager';
import { ImportPackage } from '../import-export/import-export.service.interface';

// ============================================================================
// Postman v2.1 shape (only the parts we read)
// ============================================================================

export interface PostmanCollection {
    info: {
        name: string;
        schema?: string;
        _postman_id?: string;
    };
    item: PostmanItem[];
    event?: PostmanEvent[];
    variable?: unknown[];
    auth?: PostmanAuth;
}

export interface PostmanItem {
    name: string;
    item?: PostmanItem[];
    request?: PostmanRequest;
    event?: PostmanEvent[];
    response?: unknown[];
}

export interface PostmanEvent {
    listen?: string;
    script?: { exec?: string[] | string; type?: string };
}

export interface PostmanRequest {
    method: string;
    url?: string | PostmanUrl;
    header?: PostmanHeader[];
    body?: PostmanBody;
    auth?: PostmanAuth;
    description?: string | { content: string };
}

export interface PostmanUrl {
    raw?: string;
    host?: string[];
    path?: string[];
    query?: Array<{ key: string; value: string; disabled?: boolean }>;
}

export interface PostmanHeader {
    key: string;
    value: string;
    type?: string;
    disabled?: boolean;
}

export interface PostmanBody {
    mode?: string;
    raw?: string;
}

export interface PostmanAuth {
    type: string;
    bearer?: Array<{ key: string; value: string; type?: string }>;
}

// ============================================================================
// Parser options + result
// ============================================================================

export interface PostmanParseOptions {
    /** Include request.header[] (and bearer token as Authorization) on each endpoint */
    includeHeaders: boolean;

    /**
     * If set, every imported endpoint's folder is overridden with this value.
     * If undefined, the immediate Postman parent folder is used.
     * Empty string means "root" (no folder).
     */
    targetFolder?: string;
}

export interface PostmanParseResult {
    importPackage: ImportPackage;
    /** Number of endpoints found, before user selection */
    endpointCount: number;
    /** Number of distinct headers across all endpoints (for UI display) */
    headerCount: number;
    /** Distinct folder names generated by this parse (for UI display) */
    folders: string[];
    /** Source collection name */
    collectionName: string;
    /** Things present in the collection that DBMN does not import — empty when nothing of concern */
    unsupportedFeatures: UnsupportedFeature[];
    /**
     * Per-endpoint summary of what will be dropped from THAT specific endpoint.
     * Keyed by the endpoint's freshly-generated DBMN id so the UI can flag
     * each row in the import preview.
     */
    lostByEndpointId: Record<string, EndpointLostData>;
}

/** What a specific endpoint will lose when imported. Empty fields = no loss. */
export interface EndpointLostData {
    preRequestScripts: number;
    testScripts: number;
    savedExamples: number;
    /** Body mode that's being dropped (e.g. "formdata", "urlencoded") */
    nonRawBodyMode?: string;
    /** Auth type that's being dropped (e.g. "oauth2", "apikey") */
    nonBearerAuthType?: string;
    /** Set when the request was nested deeper than one folder (parents collapsed away) */
    deeplyNested?: boolean;
}

/**
 * Per-collection detection of things that won't survive import.
 * Only emitted when at least one instance is found.
 */
export interface UnsupportedFeature {
    /** Stable ID for grouping/i18n later */
    code:
        | 'preRequestScripts'
        | 'testScripts'
        | 'savedExamples'
        | 'nonRawBodies'
        | 'nonBearerAuth'
        | 'deepFolderNesting'
        | 'collectionVariables'
        | 'collectionLevelScripts';
    /** How many endpoints / items the issue applies to */
    count: number;
    /** Short label suitable for the UI (e.g. "5 pre-request scripts") */
    label: string;
    /** Extra hint shown on hover / inline (e.g. body modes detected) */
    detail?: string;
}

// ============================================================================
// Detection
// ============================================================================

/**
 * Sniff parsed JSON to confirm it looks like a Postman collection.
 * Defensive — guards against unrelated .json files being uploaded.
 */
export function isPostmanCollection(parsed: unknown): parsed is PostmanCollection {
    if (!parsed || typeof parsed !== 'object') return false;
    const obj = parsed as Record<string, unknown>;
    const info = obj.info as Record<string, unknown> | undefined;
    if (!info || typeof info !== 'object') return false;
    if (typeof info.name !== 'string') return false;
    if (!Array.isArray(obj.item)) return false;
    if (typeof info.schema === 'string' && info.schema.includes('getpostman.com')) {
        return true;
    }
    return Array.isArray(obj.item);
}

// ============================================================================
// Parser
// ============================================================================

export class PostmanCollectionParser {
    /**
     * Parse a Postman collection JSON string into a synthetic ImportPackage.
     *
     * @param jsonString  Raw JSON text of a Postman v2.1 collection
     * @param options     Header inclusion + folder override
     * @param dobermannVersion  Extension version (for metadata; not validated against)
     */
    parse(
        jsonString: string,
        options: PostmanParseOptions,
        dobermannVersion: string = '0.0.0'
    ): PostmanParseResult {
        const parsed: unknown = JSON.parse(jsonString);
        if (!isPostmanCollection(parsed)) {
            throw new Error('File does not look like a Postman v2.1 collection');
        }
        const collection = parsed as PostmanCollection;

        const endpoints: APIEndpointConfig[] = [];
        let headerCount = 0;

        // Counters for unsupported-feature detection (issue #189 contextual warnings)
        let preRequestScripts = 0;
        let testScripts = 0;
        let savedExamples = 0;
        const nonRawBodyModes = new Set<string>();
        let nonRawBodies = 0;
        const nonBearerAuthTypes = new Set<string>();
        let nonBearerAuth = 0;
        let maxFolderAncestors = 0; // deepest leaf request's number of folder ancestors
        let deeplyNestedRequests = 0;
        const lostByEndpointId: Record<string, EndpointLostData> = {};

        const visit = (items: PostmanItem[], parentFolder: string | undefined, folderAncestors: number): void => {
            for (const item of items) {
                if (item.request) {
                    const folder = options.targetFolder !== undefined
                        ? options.targetFolder
                        : (parentFolder || '');

                    const endpoint = this.convertRequest(item, folder, options);
                    endpoints.push(endpoint);
                    headerCount += Object.keys(endpoint.headers || {}).length;

                    // Per-endpoint loss tracking — stays empty if nothing is lost.
                    const loss: EndpointLostData = {
                        preRequestScripts: 0,
                        testScripts: 0,
                        savedExamples: 0
                    };

                    if (Array.isArray(item.event)) {
                        for (const ev of item.event) {
                            if (ev.listen === 'prerequest' && this.scriptHasContent(ev.script)) {
                                preRequestScripts++;
                                loss.preRequestScripts++;
                            }
                            if (ev.listen === 'test' && this.scriptHasContent(ev.script)) {
                                testScripts++;
                                loss.testScripts++;
                            }
                        }
                    }
                    if (Array.isArray(item.response) && item.response.length > 0) {
                        savedExamples += item.response.length;
                        loss.savedExamples += item.response.length;
                    }
                    if (item.request.body && item.request.body.mode && item.request.body.mode !== 'raw') {
                        nonRawBodies++;
                        nonRawBodyModes.add(item.request.body.mode);
                        loss.nonRawBodyMode = item.request.body.mode;
                    }
                    const authType = item.request.auth?.type;
                    if (authType && authType !== 'noauth' && authType !== 'bearer') {
                        nonBearerAuth++;
                        nonBearerAuthTypes.add(authType);
                        loss.nonBearerAuthType = authType;
                    }
                    // DBMN supports a single level of folders. Flag only when a request
                    // sits inside MORE than one folder ancestor (i.e. nesting beyond
                    // the supported one level — a request directly inside a single
                    // folder is fine and not surfaced as data loss).
                    if (folderAncestors > 1) {
                        deeplyNestedRequests++;
                        loss.deeplyNested = true;
                    }
                    if (folderAncestors > maxFolderAncestors) maxFolderAncestors = folderAncestors;

                    if (this.endpointHasLoss(loss)) {
                        lostByEndpointId[endpoint.id] = loss;
                    }
                } else if (Array.isArray(item.item)) {
                    visit(item.item, item.name, folderAncestors + 1);
                }
            }
        };

        visit(collection.item, undefined, 0);

        // Collection-level scripts (pre-request / test set on the collection itself)
        let collectionLevelScripts = 0;
        for (const ev of collection.event ?? []) {
            if ((ev.listen === 'prerequest' || ev.listen === 'test') && this.scriptHasContent(ev.script)) {
                collectionLevelScripts++;
            }
        }

        const collectionVariables = Array.isArray(collection.variable) ? collection.variable.length : 0;

        const folders = Array.from(
            new Set(endpoints.map((e) => e.folder || '').filter((f) => f !== ''))
        ).sort();

        const importPackage: ImportPackage = {
            metadata: {
                version: '1.0.0',
                exportedAt: new Date().toISOString(),
                exportedBy: 'Postman Collection Import',
                dobermannVersion,
                warnings: [
                    `Imported from Postman collection: ${collection.info.name}`
                ]
            },
            endpoints: {
                version: '1.1.0',
                folders,
                endpoints
            },
            environments: {
                version: '1.2.0',
                folders: [],
                environments: []
            },
            folders: {
                version: '1.0.0',
                endpoints: { folders },
                environments: { folders: [] }
            }
        };

        const unsupportedFeatures: UnsupportedFeature[] = [];
        if (preRequestScripts > 0) {
            unsupportedFeatures.push({
                code: 'preRequestScripts',
                count: preRequestScripts,
                label: `${preRequestScripts} pre-request script${preRequestScripts === 1 ? '' : 's'}`
            });
        }
        if (testScripts > 0) {
            unsupportedFeatures.push({
                code: 'testScripts',
                count: testScripts,
                label: `${testScripts} test script${testScripts === 1 ? '' : 's'}`
            });
        }
        if (collectionLevelScripts > 0) {
            unsupportedFeatures.push({
                code: 'collectionLevelScripts',
                count: collectionLevelScripts,
                label: `${collectionLevelScripts} collection-level script${collectionLevelScripts === 1 ? '' : 's'}`
            });
        }
        if (savedExamples > 0) {
            unsupportedFeatures.push({
                code: 'savedExamples',
                count: savedExamples,
                label: `${savedExamples} saved response example${savedExamples === 1 ? '' : 's'}`
            });
        }
        if (nonRawBodies > 0) {
            unsupportedFeatures.push({
                code: 'nonRawBodies',
                count: nonRawBodies,
                label: `${nonRawBodies} non-raw body${nonRawBodies === 1 ? '' : ' requests'}`,
                detail: Array.from(nonRawBodyModes).sort().join(', ')
            });
        }
        if (nonBearerAuth > 0) {
            unsupportedFeatures.push({
                code: 'nonBearerAuth',
                count: nonBearerAuth,
                label: `${nonBearerAuth} request${nonBearerAuth === 1 ? '' : 's'} using auth other than bearer`,
                detail: Array.from(nonBearerAuthTypes).sort().join(', ')
            });
        }
        if (deeplyNestedRequests > 0) {
            unsupportedFeatures.push({
                code: 'deepFolderNesting',
                count: deeplyNestedRequests,
                label: `${deeplyNestedRequests} request${deeplyNestedRequests === 1 ? '' : 's'} nested deeper than one folder`,
                detail: `max ${maxFolderAncestors} folder levels — flattened to immediate parent`
            });
        }
        if (collectionVariables > 0) {
            unsupportedFeatures.push({
                code: 'collectionVariables',
                count: collectionVariables,
                label: `${collectionVariables} collection variable${collectionVariables === 1 ? '' : 's'}`
            });
        }

        return {
            importPackage,
            endpointCount: endpoints.length,
            headerCount,
            folders,
            collectionName: collection.info.name,
            unsupportedFeatures,
            lostByEndpointId
        };
    }

    private endpointHasLoss(loss: EndpointLostData): boolean {
        return loss.preRequestScripts > 0
            || loss.testScripts > 0
            || loss.savedExamples > 0
            || !!loss.nonRawBodyMode
            || !!loss.nonBearerAuthType
            || !!loss.deeplyNested;
    }

    private scriptHasContent(script: PostmanEvent['script'] | undefined): boolean {
        if (!script) return false;
        const exec = script.exec;
        if (!exec) return false;
        if (typeof exec === 'string') return exec.trim().length > 0;
        if (Array.isArray(exec)) return exec.some((line) => typeof line === 'string' && line.trim().length > 0);
        return false;
    }

    private convertRequest(
        item: PostmanItem,
        folder: string,
        options: PostmanParseOptions
    ): APIEndpointConfig {
        const request = item.request!;

        const path = this.extractPath(request.url);
        const queryParams = this.extractQueryParams(request.url);
        const body = this.extractBody(request.body);
        const description = this.extractDescription(request.description);
        const headers = options.includeHeaders ? this.extractHeaders(request) : {};

        return {
            id: generateEndpointId(),
            name: item.name,
            method: this.normalizeMethod(request.method),
            path,
            headers,
            queryParams,
            body: body || undefined,
            description,
            folder: folder || undefined
        };
    }

    private normalizeMethod(method: string | undefined): 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE' {
        const upper = (method ?? 'GET').toUpperCase();
        if (upper === 'GET' || upper === 'POST' || upper === 'PUT' || upper === 'PATCH' || upper === 'DELETE') {
            return upper;
        }
        return 'GET';
    }

    private extractPath(url: string | PostmanUrl | undefined): string {
        if (!url) return '/';
        const segments = typeof url === 'string'
            ? this.parseRawUrlSegments(url)
            : (url.path ?? this.parseRawUrlSegments(url.raw ?? ''));

        const cleaned = segments
            .map((s) => String(s).trim())
            .filter((s) => s.length > 0 && !this.isHostSegment(s));

        return '/' + cleaned.join('/');
    }

    /**
     * Extract path segments from a raw URL string (used as a fallback when
     * `url.path` is not present). Strips scheme/host and Postman variable
     * placeholders that look like a host (e.g. {{url}}).
     */
    private parseRawUrlSegments(raw: string): string[] {
        if (!raw) return [];
        let working = raw;
        const schemeIdx = working.indexOf('://');
        if (schemeIdx >= 0) {
            working = working.substring(schemeIdx + 3);
            const slash = working.indexOf('/');
            working = slash >= 0 ? working.substring(slash + 1) : '';
        } else if (working.startsWith('{{') && working.includes('}}/')) {
            working = working.substring(working.indexOf('}}/') + 3);
        } else if (working.startsWith('/')) {
            working = working.substring(1);
        }
        const queryIdx = working.indexOf('?');
        if (queryIdx >= 0) working = working.substring(0, queryIdx);
        return working.split('/').filter((s) => s.length > 0);
    }

    private isHostSegment(segment: string): boolean {
        // Treat a single Postman variable placeholder at the start as a host (e.g. "{{url}}")
        return /^\{\{[^}]+\}\}$/.test(segment);
    }

    private extractQueryParams(url: string | PostmanUrl | undefined): Record<string, string> {
        if (!url || typeof url === 'string') return {};
        const params: Record<string, string> = {};
        for (const q of url.query ?? []) {
            if (!q.disabled && q.key) {
                params[q.key] = q.value ?? '';
            }
        }
        return params;
    }

    private extractBody(body: PostmanBody | undefined): string {
        if (!body || body.mode !== 'raw') return '';
        return body.raw ?? '';
    }

    private extractDescription(desc: string | { content: string } | undefined): string {
        if (!desc) return '';
        if (typeof desc === 'string') return desc;
        return desc.content ?? '';
    }

    private extractHeaders(request: PostmanRequest): Record<string, string> {
        const headers: Record<string, string> = {};
        for (const h of request.header ?? []) {
            if (h.disabled || !h.key) continue;
            headers[h.key] = h.value ?? '';
        }
        if (request.auth?.type === 'bearer' && Array.isArray(request.auth.bearer)) {
            const hasAuth = Object.keys(headers).some((k) => k.toLowerCase() === 'authorization');
            if (!hasAuth) {
                const tokenEntry = request.auth.bearer.find((b) => b.key === 'token');
                if (tokenEntry?.value) {
                    headers['Authorization'] = tokenEntry.value;
                }
            }
        }
        return headers;
    }
}
